// 草稿初筛的判据，单一出口：初筛.mjs（命令行）与 写片.mjs（写完后自动筛）都从这里取，
// 免得两边规则各改一遍。
//
// 2026-11-09 修一个真 bug：以前扫的是整张草稿，而「写片.mjs」自己在抬头里写了
// 「输入 1889 / 输出 236 token」——于是**每一份草稿都必然命中 .接口术语×1**，
// 一律被判弃。11-07 一天十几份稿子全进了 _弃，就是这么来的。
// 现在只扫 `---` 之后的正文；抬头的用量行不进判据。
//
// 阈值也从「接口词 ≥1 就弃」放宽到 ≥3：正文里偶然带一个 token/HTTP
// 不等于通篇流水，而真流水（旧那批）一篇里都有一串。
//
// 判据来源是一次对照实测（2026-11-01）：26 份成品 vs 43 份草稿。
// 路径/脚本名/代码块那几条误伤为 0、但砍中只有 3/43——所以它们是补充，不是主力。

const 接口词 = /\b(API|token|PID|exit|JSON|HTTP|WebHook|NaN|null)\b/gi;
const 硬规则 = [
  ['.路径', /[A-Za-z]:\\|D:\\|C:\\/],
  ['.脚本名', /[\w-]+\.(mjs|ps1|py|json|jsonl|yml|yaml)\b/i],
  ['.命令行', /\bnode\s+\S+|--[\w一-龥]+=/],
  ['.代码块', /```/],
  ['.系统术语', /端口|进程号|环境变量|正则|哈希|mtime|UTF-?8|编码/],
];

// 去掉写片.mjs 自己那截抬头（`---` 分隔线以上）。没有分隔线就返回原文。
function 取正文(t) {
  const m = String(t || '').match(/^[\s\S]*?\r?\n---\r?\n/);
  return m ? String(t).slice(m[0].length) : String(t || '');
}

// 返回 {判:'弃'|'留', 命中:[...]}。命中为空即「留」（进待审）。
export function 判草稿(t) {
  const 正文 = 取正文(t);
  const 命中 = 硬规则.filter(([, re]) => re.test(正文)).map(([n]) => n);
  const 接口数 = (正文.match(接口词) || []).length;
  if (接口数 >= 3) 命中.push(`.接口术语×${接口数}`);
  const 事实 = (正文.match(/##\s*事实\s*\n([\s\S]*?)(?=\n##\s|$)/) || [, ''])[1]
    .replace(/\s/g, '');
  if (事实.length < 60) 命中.push('.事太短');
  if (正文.replace(/\s/g, '').length < 200) 命中.push('.整篇太短');
  return { 判: 命中.length ? '弃' : '留', 命中 };
}
