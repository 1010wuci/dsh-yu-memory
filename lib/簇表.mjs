// 判一片归哪个主簇：话题命中 3 分、关键词命中 1 分，取最高；0 分返回 null（记「没主簇」）。
// 2026-10-31 修一个真 bug：原来是纯子串匹配，「交接单」里的「接单」把一篇讲交接单的片判成了接单。
// 现在的规矩：
//   · 话题按顿号/逗号切成小段，两字词只认整段相等（免得「交接单」撞上「接单」）；
//   · 三字以上的词才允许在段内或关键词里做子串（「接单雷达」还能认出来）；
//   · 单字只在关键词一侧按包含算（「旧账」里的「账」是弱信号）。
const 切段 = s => String(s).toLowerCase().split(/[，,、／/；;：:|\s]+/).filter(Boolean);

export function 判主簇(话题, 关键词们, 表 = SEEDS, 宽词 = null) {
  const kw = (关键词们 || []).map(k => String(k).toLowerCase());
  const 段 = 切段(话题);
  let best = null;
  for (const [main, syn] of 表) {
    let score = 0;
    for (const w of syn) {
      if (!w) continue;
      const s = String(w).toLowerCase();
      const 长 = [...s].length;
      // 宽词（鱼自己加的）两字也允许子串：那是它为自己的话挑的词，不是公共表那种会撞车的泛词。
      // 公共表仍按老规矩：两字只认整段相等，免得「交接单」撞「接单」。
      const 可容 = 长 >= 3 || (宽词 && 宽词.has(s));
      if (长 >= 2 && 段.some(x => x === s || (可容 && x.includes(s)))) score += 3;
      if (长 >= 3 ? kw.some(k => k === s || k.includes(s)) : 长 === 2 ? kw.some(k => k === s) : kw.some(k => k.includes(s))) score += 1;
    }
    if (score && (!best || score > best.score)) best = { main, score };
  }
  return best;
}

// 每条鱼自己的补充表（2026-11-09 加）：库根下的 `_簇表-本地.json`。
// 为什么要有它：公共表是骨架，写死的；可鱼有它自己的日子——「挑第六个」「被主人说傻」
// 这种片套不上任何公共簇。若每遇到一种就改公共表，十条鱼各改一版，又回到「每条鱼一套」。
// 所以：公共表不动，鱼自己往这个文件里加词、加簇，只影响它自己。
//
// 结构：
//   {
//     "加词": { "相处": ["被主人说傻", "语气词"] },
//     "加簇": [ { "簇": "天气", "词": ["下雨","热"], "谁": "鱼", "何时": "2026-11-09T…", "因": "…" } ]
//   }
// 规矩：加词随便加（上限见 每簇词上限）；加簇要写「因」，且总数不能顶到 簇数上限。
export const 每簇词上限 = 30;

export function 读本地表(库根) {
  try {
    const o = JSON.parse(readFileSync(join(库根, '_簇表-本地.json'), 'utf8'));
    const 加词 = (o && o.加词 && typeof o.加词 === 'object') ? o.加词 : {};
    const 加簇 = (o && Array.isArray(o.加簇)) ? o.加簇.filter(x => x && x.簇) : [];
    return { 加词, 加簇 };
  } catch {
    return { 加词: {}, 加簇: [] };
  }
}

// 公共表 + 本地表合成一张能直接判的表：公共簇在前（同分时公共优先），本地新簇在后。
export function 合并表(库根) {
  const 本 = 读本地表(库根);
  const 表 = SEEDS.map(([名, 词们]) => {
    const 加 = Array.isArray(本.加词[名]) ? 本.加词[名] : [];
    const 有 = new Set(词们.map(w => String(w).toLowerCase()));
    const 补 = 加.map(w => String(w)).filter(w => w && !有.has(w.toLowerCase()));
    return [名, 词们.concat(补)];
  });
  const 已有 = new Set(SEEDS.map(([n]) => n));
  for (const c of 本.加簇) {
    if (已有.has(c.簇)) continue;           // 公共表里已经有的名字，只认加词，不重复开簇
    if (表.length >= 簇数上限) break;        // 到顶就不再开，只许合并
    表.push([c.簇, (Array.isArray(c.词) ? c.词.map(String) : []).filter(Boolean)]);
  }
  return 表;
}

// 人工裁定表：规则判不出、或最高分撞车的片，最终归哪个簇由我定。
// 表在库根 _主簇覆盖.json，模型只出候选，这里才是结论。没有这份表就当空表。
export function 读覆盖(库根) {
  const 读 = p => { try { return JSON.parse(readFileSync(p, 'utf8')).覆盖 || {}; } catch { return null; } };
  const 自己 = 读(join(库根, '_主簇覆盖.json'));
  if (自己 && Object.keys(自己).length) return 自己;
  // 测库是整份复制的，裁定表常常没跟着复制过来；那就以真库的为准。
  // 不然归档会把「我定过的簇」重新按规则算一遍，库和星图就对不上。
  // 只认自己库里的裁定表；测库没带就是空表，不偷读本机真库（搬包给别人时那条路径不存在）
  return 自己 || {};
}

// 定一片的最终主簇：先看裁定表，再退回规则。分主簇和归档都走这一个口子，
// 免得归档写进库的簇和星图算的簇对不上（2026-10-31 真出过一次：0138 归档判余额，裁定表写的是记忆库）。
export function 定主簇(库根, id, 话题, 关键词们) {
  // 按标题优先、编号兜底（2026-11-02 修）：裁定表 2026-10-31 已从编号键迁成标题键，
  // 这里却一直只按 id 查 → 标题键的裁定一条都命中不到，重建索引/归档出来的片全变「没主簇」
  // （真库复算一次就冒出 55 片，测试鱼 y0006 更狠）。编号键仍认，兼容还没迁的表。
  const 覆 = 读覆盖(库根);
  const o = (话题 && 覆[话题]) || 覆[id];
  if (o && o.簇) return { main: o.簇, score: null, 来源: o.来源 || '人工裁定', 因: o.因 || '' };
  // 裁定表没有，才按规则算；规则用的是「公共表 + 这条鱼自己的补充表」（2026-11-09 加）。
  const 本 = 读本地表(库根);
  const 宽词 = new Set();
  for (const [, 词们] of Object.entries(本.加词 || {})) {
    if (Array.isArray(词们)) for (const w of 词们) if (w) 宽词.add(String(w).toLowerCase());
  }
  for (const c of 本.加簇) {
    if (Array.isArray(c.词)) for (const w of c.词) if (w) 宽词.add(String(w).toLowerCase());
  }
  const 判 = 判主簇(话题, 关键词们, 合并表(库根), 宽词);
  if (!判) return 判;
  const 是本地簇 = 本.加簇.some(c => c.簇 === 判.main);
  return 是本地簇 ? { ...判, 来源: '本地簇' } : 判;
}

// 种子簇不是越多越好：簇一多，每片的归属就会变糊，人也看不过来。
// 上限 40；到 36 开始预警，到顶就只许合并、不许新开。新簇一律先进候选，攒够三片再升。
export const 簇数上限 = 40;
export const 簇数预警 = 36;
export function 还能开新簇() {
  return { 现有: SEEDS.length, 上限: 簇数上限, 还能开: 簇数上限 - SEEDS.length, 已预警: SEEDS.length >= 簇数预警 };
}

